def norm(s):
    s = '' if s is None else str(s)
    s = unicodedata.normalize('NFKC', s).lower()
    return re.sub(r'[\s\-_—()（）【】\[\]{}:：,，.!！？/、\'"·。]+', '', s)

def base_parts(s):
    s = str(s)
    s = re.sub(r'[（(].*?[）)]', '', s)
    return [norm(x) for x in re.split(r'[/／]', s) if norm(x)]

