def find_candidates(req_no, req_title):
    exact=[]
    seen=set()
    for p in base_parts(req_title):
        for row in by_name.get(p, []):
            if row[0] not in seen:
                exact.append(row); seen.add(row[0])
    if exact:
        return [(row, '匹配', '曲名同名或括号别名一致') for row in exact]
    out=[]
    for name, reason, status in alias_map.get(req_no, []):
        for row in by_name.get(norm(name), []):
            out.append((row, status, reason))
    return out

